type Foundation = NonNullable<StarterLesson['foundation']>
type Context = Omit<StarterLesson['transfer'][number], 'id'>
type Seed = {
  position: number; titleZh: string; goalZh: string; model: StarterLesson['model']
  otherMeanings: [string, string]; pieces: string[]; accepted: string[]
  errors: StarterLesson['expression']['errors']; contexts: Context[]; foundation: Foundation
}
function model(text: string, reading: string, romaji: string, meaningZh: string, explanationZh: string): StarterLesson['model'] {
  return { text, reading, romaji, meaningZh, explanationZh }
}
function context(promptZh: string, reference: string, romaji: string, meaningZh: string, explanationZh: string, alternatives: string[]): Context {
  return { promptZh, reference, romaji, meaningZh, explanationZh, accepted: [reference, ...alternatives] }
}
function foundation(titleZh: string, explanationZh: string, examples: Foundation['examples'], sourceUrl: string,
  sourceInstructionZh: string, promptZh: string, choices: [string, string, string], answerIndex = 0): Foundation {
  return { titleZh, explanationZh, examples, sourceUrl, sourceInstructionZh,
    check: { promptZh, choices: choices.map((textZh, index) => ({ id: `option-${index}`, textZh })),
      answerId: `option-${answerIndex}`, explanationZh: `先对照刚才教过的文字：${choices[answerIndex]}。这里只检查文字与说明的对应，不检查听音、口音或音高。` } }
}
function hiragana(glyphs: string[], roman: string[], target: number, explanationZh: string): Foundation {
  return foundation(`一小组平假名：${glyphs.join('・')}`, explanationZh,
    glyphs.map((text, index) => ({ text, meaningZh: `临时罗马字提示 ${roman[index]}；单个假名不等于一个有词义的汉字。` })), sources.hiragana,
    `打开 Hiragana 表，找到 ${glyphs.join('、')}，逐字对照字形和参考声音。打不开时先做本页文字配对，不记成已听音。`,
    `刚教过的字形 ${glyphs[target]} 对应哪个临时提示？不用猜没学过的字，也不用输入日语。`,
    [roman[target]!, roman[(target + 1) % glyphs.length]!, roman[(target + 2) % glyphs.length]!])
}
function freeze<T>(value: T): T {
  if (value !== null && typeof value === 'object') {
    for (const child of Object.values(value)) freeze(child)
    Object.freeze(value)
  }
  return value
}
function course(seed: Seed): StarterLesson {
  const id = `ja-starter-${seed.position}`
  return { id, language: 'ja', version: 1, position: seed.position, titleZh: seed.titleZh, goalZh: seed.goalZh,
    prerequisites: [`ja-starter-${seed.position - 1}`], minutes: { quick: 5, standard: 10 }, model: seed.model,
    recognition: { promptZh: `在本课情境中，${seed.model.text} 要表达什么？先看已讲的意思，再选。`,
      choices: [{ id: 'meaning', textZh: seed.model.meaningZh }, ...seed.otherMeanings.map((textZh, index) => ({ id: `other-${index}`, textZh }))],
      answerId: 'meaning', explanationZh: `${seed.model.meaningZh} ${seed.model.explanationZh}` },
    scaffold: { promptZh: `用已讲过的词块组好一句：${seed.model.meaningZh}。可点选，不要求输入法。`,
      pieces: seed.pieces, answer: seed.model.text, explanationZh: seed.model.explanationZh },
    expression: { promptZh: seed.goalZh, reference: seed.model.text, accepted: [seed.model.text, ...seed.accepted], errors: seed.errors },
    transfer: seed.contexts.map((item, index) => ({ ...item, id: `${id}-context-${index + 1}` })), foundation: seed.foundation,
    sound: { sourceLabel: '本站原创教学；日本国际交流基金 MARUGOTO Plus 真人读音参考（外链，非本句录音）',
      sourceUrl: seed.foundation.sourceUrl, status: 'pending-review',
      notesZh: '尚无本句经人工核对的示范音频。外链供字形和读音参考，不声称那里收录了这句原创例句。无法播放可继续文字／选句；罗马字只是可关闭的临时帮助，不表示完整音高，不作声学评分。' } }
}

